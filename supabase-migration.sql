-- Secure order tracking: customer must provide both order id and the phone stored on that order.
create or replace function public.track_order_by_phone(p_order_id text, p_phone text)
returns table(id text, status text, amount_toman numeric, created_at timestamptz)
language sql security definer set search_path = public
as $$
  select o.id::text, o.status::text, o.amount::numeric, o.created_at
  from public.vm_orders o
  where o.id::text = p_order_id
    and regexp_replace(coalesce(o.customer_phone,''), '\D', '', 'g') = regexp_replace(coalesce(p_phone,''), '\D', '', 'g')
  limit 1;
$$;
revoke all on function public.track_order_by_phone(text,text) from public;
grant execute on function public.track_order_by_phone(text,text) to anon, authenticated;

-- Product variants: flavors, colors, and models with independent inventory.
create table if not exists public.vm_product_variants (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.vm_products(id) on delete cascade,
  label text not null check (char_length(label) between 1 and 100),
  variant_type text not null check (variant_type in ('flavor','color','model')),
  stock integer not null default 0 check (stock >= 0),
  price_override bigint check (price_override is null or price_override >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
