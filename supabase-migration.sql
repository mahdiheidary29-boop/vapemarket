-- VapePad Market migration
-- Run this in Supabase Dashboard > SQL Editor.
-- This does not delete existing products or orders.

alter table public.vm_products
  add column if not exists stock integer not null default 0,
  add column if not exists discount_percent numeric(5,2) not null default 0;

alter table public.vm_products
  drop constraint if exists vm_products_stock_nonnegative;
alter table public.vm_products
  add constraint vm_products_stock_nonnegative check (stock >= 0);

alter table public.vm_products
  drop constraint if exists vm_products_discount_range;
alter table public.vm_products
  add constraint vm_products_discount_range check (discount_percent >= 0 and discount_percent <= 100);

alter table public.vm_orders
  add column if not exists delivery_method text,
  add column if not exists device_check text,
  add column if not exists shipping_cost_payer text default 'customer',
  add column if not exists customer_name text,
  add column if not exists customer_phone text,
  add column if not exists customer_address text;

create table if not exists public.support_tickets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject text not null check (char_length(subject) between 1 and 120),
  message text not null check (char_length(message) between 1 and 2000),
  status text not null default 'open' check (status in ('open','answered','closed')),
  admin_reply text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.support_tickets enable row level security;

drop policy if exists "Users can create own support tickets" on public.support_tickets;
create policy "Users can create own support tickets"
on public.support_tickets for insert to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users can read own support tickets" on public.support_tickets;
create policy "Users can read own support tickets"
on public.support_tickets for select to authenticated
using (auth.uid() = user_id);

-- Admin policies for tickets. Admin UUID is the existing VapeMarket owner account.
drop policy if exists "VapePad admin can read all tickets" on public.support_tickets;
create policy "VapePad admin can read all tickets"
on public.support_tickets for select to authenticated
using (auth.uid() = '55422178-aed3-4eb7-9b0f-9301304125c3'::uuid);

drop policy if exists "VapePad admin can update tickets" on public.support_tickets;
create policy "VapePad admin can update tickets"
on public.support_tickets for update to authenticated
using (auth.uid() = '55422178-aed3-4eb7-9b0f-9301304125c3'::uuid)
with check (auth.uid() = '55422178-aed3-4eb7-9b0f-9301304125c3'::uuid);

